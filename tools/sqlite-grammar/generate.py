#!/usr/bin/env python3
"""
Generates SqliteGrammar.g.cs, SQLite's LALR(1) parser tables and keyword list, from a SQLite source tree.

SQLite's parser is generated by Lemon from parse.y; parse.c holds the tables. Porting the tables, not the grammar,
makes this library accept exactly the SQL that SQLite accepts. Run it again when moving to a newer SQLite:

    python3 tools/sqlite-grammar/generate.py <dir with parse.c and mkkeywordhash.c> <version>

parse.c comes from a SQLite amalgamation or a built source tree (it is generated, so it is not in the repository at
github.com/sqlite/sqlite). mkkeywordhash.c is tool/mkkeywordhash.c in that repository.
"""
import re
import sys
from pathlib import Path

src = Path(sys.argv[1])
version = sys.argv[2]
parse_c = (src / "parse.c").read_text()
keywords_c = (src / "mkkeywordhash.c").read_text()


def array(name):
    m = re.search(r"\b" + re.escape(name) + r"\[\] = \{(.*?)\n\};", parse_c, re.S)
    body = re.sub(r"/\*.*?\*/", "", m.group(1), flags=re.S)
    return [int(x) for x in re.findall(r"-?\d+", body)]


def strings(name):
    m = re.search(r"\b" + re.escape(name) + r"\[\] = \{(.*?)\n\};", parse_c, re.S)
    return re.findall(r'"((?:[^"\\]|\\.)*)"', re.sub(r"/\*.*?\*/", "", m.group(1), flags=re.S))


def define(name):
    return int(re.search(r"#define " + name + r"\s+\(?(-?\d+)\)?", parse_c).group(1))


tokens = [(m.group(1), int(m.group(2))) for m in re.finditer(r"#define TK_(\w+)\s+(\d+)", parse_c)]
seen = set()
tokens = [t for t in tokens if not (t[0] in seen or seen.add(t[0]))]

# Keywords whose feature mask is enabled in a default build (no SQLITE_OMIT_*, no SQLITE_ENABLE_ORDERED_SET_AGGREGATES)
disabled = {"ORDERSET"}
table = re.search(r"static Keyword aKeywordTable\[\] = \{(.*?)\n\};", keywords_c, re.S).group(1)
keywords = []
for m in re.finditer(r'\{\s*"(\w+)",\s*"TK_(\w+)",\s*([\w|]+),', table):
    if not set(m.group(3).split("|")) & disabled:
        keywords.append((m.group(1), m.group(2)))

consts = ["YYNSTATE", "YYNRULE", "YYNTOKEN", "YY_MAX_SHIFT", "YY_MIN_SHIFTREDUCE", "YY_MAX_SHIFTREDUCE",
          "YY_ERROR_ACTION", "YY_ACCEPT_ACTION", "YY_NO_ACTION", "YY_MIN_REDUCE", "YY_MAX_REDUCE", "YYWILDCARD",
          "YYNOCODE", "YY_SHIFT_COUNT", "YY_REDUCE_COUNT", "YY_ACTTAB_COUNT"]


def cs_array(type_, name, values):
    lines = []
    for i in range(0, len(values), 20):
        lines.append("        " + ", ".join(str(v) for v in values[i:i + 20]) + ",")
    return f"    public static readonly {type_}[] {name} =\n    {{\n" + "\n".join(lines) + "\n    };\n"


def cs_strings(name, values):
    lines = ["        \"" + v + "\"," for v in values]
    return f"    public static readonly string[] {name} =\n    {{\n" + "\n".join(lines) + "\n    };\n"


out = []
out.append("// <auto-generated>")
out.append(f"// Generated by tools/sqlite-grammar/generate.py from SQLite {version}'s parse.c and tool/mkkeywordhash.c.")
out.append("// Do not edit; run the script again instead. SQLite is in the public domain.")
out.append("// </auto-generated>")
out.append("")
out.append("namespace MBW.Utilities.ManagedSqlite.Sql.Internal.Grammar;")
out.append("")
out.append("/// <summary>")
out.append("/// SQLite's token codes (TK_* in parse.h)")
out.append("/// </summary>")
out.append("internal static class TK")
out.append("{")
for n, v in tokens:
    out.append(f"    public const int {n} = {v};")
out.append("}")
out.append("")
out.append("/// <summary>")
out.append(f"/// SQLite {version}'s Lemon parser tables (parse.c) and keywords (mkkeywordhash.c)")
out.append("/// </summary>")
out.append("internal static class SqliteGrammar")
out.append("{")
out.append(f"    public const string Version = \"{version}\";")
for c in consts:
    out.append(f"    public const int {c} = {define(c)};")
out.append("")
out.append(cs_array("ushort", "Action", array("yy_action")))
out.append(cs_array("ushort", "Lookahead", array("yy_lookahead")))
out.append(cs_array("ushort", "ShiftOffset", array("yy_shift_ofst")))
out.append(cs_array("short", "ReduceOffset", array("yy_reduce_ofst")))
out.append(cs_array("ushort", "Default", array("yy_default")))
out.append(cs_array("ushort", "Fallback", array("yyFallback")))
out.append(cs_array("ushort", "RuleLhs", array("yyRuleInfoLhs")))
out.append(cs_array("sbyte", "RuleRhsCount", array("yyRuleInfoNRhs")))
out.append(cs_strings("RuleNames", strings("yyRuleName")))
out.append(cs_strings("TokenNames", strings("yyTokenName")))
out.append("    /// <summary>")
out.append("    /// The keywords and their token codes, as sqlite3KeywordCode in keywordhash.h finds them")
out.append("    /// </summary>")
out.append("    public static readonly (string Keyword, int Token)[] Keywords =")
out.append("    {")
for k, t in keywords:
    out.append(f"        (\"{k}\", TK.{t}),")
out.append("    };")
out.append("}")

Path(sys.argv[3] if len(sys.argv) > 3 else "SqliteGrammar.g.cs").write_text("\n".join(out) + "\n")
